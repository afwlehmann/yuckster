// The object literal above is intentionally incomplete; the following fills in the
// remaining arrow/glyph entries via a small post-step to keep the table readable.
const EXTRA: Readonly<Record<string, readonly number[]>> = {
  '(': [0x04, 0x08, 0x10, 0x10, 0x10, 0x08, 0x04],
  ')': [0x04, 0x02, 0x01, 0x01, 0x01, 0x02, 0x04],
  '<': [0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02],
  '>': [0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08],
  '*': [0, 0x11, 0x0a, 0x1f, 0x0a, 0x11, 0],
};

const ALL = { ...GLYPHS, ...EXTRA } as Readonly<Record<string, readonly number[]>>;

export const GLYPH_W = 5;
export const GLYPH_H = 7;

const glyphFor = (ch: string): readonly number[] | undefined => ALL[ch];

export interface TextDraw {
  readonly ctx: CanvasRenderingContext2D;
  readonly x: number;
  readonly y: number;
  readonly color: string;
  readonly scale: number;
}

/** Draw a single character (uppercase A-Z, 0-9, basic punctuation). */
export const drawChar = (draw: TextDraw, ch: string): void => {
  const glyph = glyphFor(ch.toUpperCase());
  if (glyph === undefined) return;
  const { ctx, x, y, color, scale } = draw;
  ctx.fillStyle = color;
  for (let row = 0; row < GLYPH_H; row += 1) {
    const bits = glyph[row];
    for (let col = 0; col < GLYPH_W; col += 1) {
      if ((bits >> (GLYPH_W - 1 - col)) & 1) {
        ctx.fillRect(x + col * scale, y + row * scale, scale, scale);
      }
    }
  }
};

/** Draw a string left-aligned at (x,y). Returns the width consumed. */
export const drawText = (
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): number => {
  const spacing = GLYPH_W + 1;
  let cursor = x;
  for (const ch of text) {
    drawChar({ ctx, x: cursor, y, color, scale }, ch);
    cursor += spacing * scale;
  }
  return cursor - x;
};

/** Right-align text ending at x. */
export const drawTextRight = (
  ctx: CanvasRenderingContext2D,
  text: string,
  endX: number,
  y: number,
  color: string,
  scale = 1,
): void => {
  const spacing = GLYPH_W + 1;
  const width = text.length * spacing * scale;
  drawText(ctx, text, endX - width, y, color, scale);
};

/** Center text at x. */
export const drawTextCenter = (
  ctx: CanvasRenderingContext2D,
  text: string,
  centerX: number,
  y: number,
  color: string,
  scale = 1,
): void => {
  const spacing = GLYPH_W + 1;
  const width = text.length * spacing * scale;
  drawText(ctx, text, centerX - width / 2, y, color, scale);
};

export const textWidth = (text: string, scale = 1): number => {
  const spacing = GLYPH_W + 1;
  return text.length * spacing * scale;
};
